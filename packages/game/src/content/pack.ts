const perimeter = (id: string, penalty?: Unlock[]): Unlock => ({
	t: 'perimeter',
	bundle: bundleId(id),
	...(penalty ? { penalty } : {}),
});

function card(
	month: number,
	sequence: number,
	halt: 'pause' | 'stop',
	title: string,
	text: string,
	unlocks: Unlock[],
): LegacyCardDef {
	return {
		id: `${String(month).padStart(2, '0')}-${String(sequence).padStart(2, '0')}`,
		month,
		halt,
		title,
		text,
		unlocks,
	};
}

