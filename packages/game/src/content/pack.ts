function route(
	id: string,
	at: string,
	color: Color,
	count: number,
	unique: boolean,
	opens: string,
	counts: ObjectiveId[],
	needsCenter = true,
): ReconRoute {
	return { id, city: city(at), color, count, unique, opens: bundleId(opens), needsCenter, counts };
}

